import Foundation

/// A detection event surfaced in the Events tab for a patient. The
/// `category` + `opened` + `reviewed` triplet drives the event-card
/// state matrix (per design system §05 Components / Event card).
struct DetectionEvent: Identifiable, Hashable, Sendable {
    let id: UUID
    var patientId: UUID
    var detectorId: UUID?       // nil when generated by a preset that hasn't been instantiated yet
    var category: Detector.Category
    var source: Detector.Source
    var iconName: String        // SF Symbol used on the card's icon tile
    var title: String           // "Possible fall"
    var location: String        // "Living room"
    var time: String            // human label: "14:32" / "Yesterday 02:30"
    var ago: String             // "42 min ago" / "13h ago"
    var hasClip: Bool           // safety events have a clip; routine events don't
    var narrative: String       // VLM-written paragraph for Event Detail
    var opened: Bool
    var reviewed: Bool

    /// The caregiver's choice from the Event Review step.
    enum ReviewChoice: String, Sendable {
        case correct
        case wrong
        case unsure
    }

    var reviewChoice: ReviewChoice?
    var reviewNotes: String?
}
